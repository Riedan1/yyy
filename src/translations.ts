/**
 * Heuristically detects the browser language, defaulting to "en" as fallback.
 * Checks for stored preference first.
 */
export function detectBrowserLanguage(): Language {
  try {
    const stored = localStorage.getItem("dz_language");
    if (stored === "en" || stored === "ar") {
      return stored as Language;
    }
  } catch (e) {}
  return "en";
}

/**
 * Saves the selected language to localStorage and configures the DOM direction
 * (dir="rtl" for Arabic, dir="ltr" for French/English).
 */
export function setLanguageInDOM(lang: Language) {
  try {
    localStorage.setItem("dz_language", lang);
  } catch (e) {}
  
  if (typeof document !== "undefined") {
    const htmlElement = document.documentElement;
    if (lang === "ar") {
      htmlElement.setAttribute("dir", "rtl");
      htmlElement.setAttribute("lang", "ar");
    } else {
      htmlElement.setAttribute("dir", "ltr");
      htmlElement.setAttribute("lang", lang);
    }
  }
}

/**
 * Translates a key according to the active language.
 */
export function translate(key: string, lang: Language): string {
  const dict = translations[lang] || translations["en"];
  return (dict as any)[key] || key;
}
